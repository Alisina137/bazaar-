import console from "node:console";
import process from "node:process";
import { readFileSync } from "node:fs";
const env=process.env;
const blockers=[];
const warnings=[];
const https=(v)=>typeof v==="string" && /^https:\/\//i.test(v);
const app=JSON.parse(readFileSync("apps/mobile/app.json","utf8"));
const eas=JSON.parse(readFileSync("apps/mobile/eas.json","utf8"));
if(env.NODE_ENV!=="production") blockers.push("NODE_ENV=production required for real launch");
if(!/^postgres(?:ql)?:\/\//i.test(env.DATABASE_URL??"")) blockers.push("production DATABASE_URL missing");
if(!https(env.API_PUBLIC_BASE_URL)) blockers.push("API_PUBLIC_BASE_URL must be HTTPS");
if(!https(env.EXPO_PUBLIC_API_URL)) blockers.push("EXPO_PUBLIC_API_URL must be production HTTPS");
if(!https(env.NEXT_PUBLIC_API_URL)) blockers.push("NEXT_PUBLIC_API_URL must be production HTTPS");
if(env.HESABPAY_API_KEY && env.HESABPAY_ENVIRONMENT!=="production") blockers.push("Live payment key cannot run in sandbox mode");
if(env.HESABPAY_API_KEY && !https(env.PAYMENT_PUBLIC_BASE_URL)) blockers.push("Live hosted payment redirect must use HTTPS");
if(!env.HESABPAY_API_KEY) warnings.push("Digital payments unavailable: use COD/pickup for pilot or configure and test a live gateway");
if(!app.expo.android?.package) blockers.push("Confirm production Android package ID");
if(eas.build.production.android.buildType!=="app-bundle") blockers.push("Production Android App Bundle profile missing");
warnings.push("Validate signing credentials, privacy policy, official logo, Play Store assets and release compliance manually");
warnings.push("Merchant self-serve paid upgrades remain blocked in production until independently verified billing is implemented");
warnings.push("Verify production backups and restore, real-device RTL/accessibility, delivery coverage and provider webhooks");
console.log("Production preflight (does not print secrets)");
for (const item of blockers) console.error("BLOCKED: "+item);
for (const item of warnings) console.log("MANUAL: "+item);
if(blockers.length) process.exitCode=1;
else console.log("Environment static checks passed; manual go/no-go gates still apply.");
